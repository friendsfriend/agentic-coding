// Build-time only: the packaged executable embeds these bytes and never invokes
// a compiler on the user's machine. SQLite symbols come from its extension API.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

if (process.platform !== "darwin" && process.platform !== "linux")
	throw new Error("Secure workflow SQLite supports macOS and Linux.");
const root = path.resolve(import.meta.dir, ".."),
	temporary = fs.mkdtempSync(path.join(os.tmpdir(), "herdr-sqlite-build-"));
try {
	const output = path.join(
		temporary,
		process.platform === "darwin" ? "secure-sqlite.dylib" : "secure-sqlite.so",
	);
	const result = Bun.spawnSync(
		[
			process.env.CC ?? "cc",
			"-std=c11",
			"-O2",
			"-Wall",
			"-Wextra",
			"-Werror",
			"-fPIC",
			...(process.platform === "darwin" ? ["-dynamiclib"] : ["-shared"]),
			path.join(root, "src/workflow/native/secure-sqlite.c"),
			"-o",
			output,
		],
		{ stdout: "inherit", stderr: "inherit" },
	);
	if (result.exitCode !== 0)
		throw new Error(
			"Secure SQLite extension build failed (requires a C compiler and public SQLite development headers).",
		);
	const data = {
		platform: process.platform,
		arch: process.arch,
		base64: fs.readFileSync(output).toString("base64"),
	};
	fs.writeFileSync(
		path.join(root, "src/workflow/native/extension.generated.ts"),
		`// Generated by scripts/build-secure-sqlite.ts; do not edit.\nexport const secureSqliteExtension = {\n\tplatform: ${JSON.stringify(data.platform)},\n\tarch: ${JSON.stringify(data.arch)},\n\tbase64:\n\t\t${JSON.stringify(data.base64)},\n};\n`,
	);
} finally {
	fs.rmSync(temporary, { recursive: true, force: true });
}
