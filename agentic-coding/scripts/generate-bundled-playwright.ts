#!/usr/bin/env bun
// Generates `src/server/browser/bundled-playwright.generated.ts`: the Playwright
// version and the Chromium revision this build bundles.
//
// The browser installer reads those two values from the installed
// `playwright-core` package when it can (a source checkout). A compiled
// executable cannot: the package's manifest is inside the bundle, not a file on
// disk, so the lookup falls back to this generated module — which is what makes
// the "install the revision *this* build expects" rule hold in the artifact users
// actually run, instead of silently accepting whatever revision an earlier
// version left behind.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dir, "..");
const packageDir = path.join(root, "node_modules", "playwright-core");
const out = path.join(
	root,
	"src",
	"server",
	"browser",
	"bundled-playwright.generated.ts",
);

/** Read the bundled Playwright version, or `""` when it is not installed. */
function readVersion(): string {
	try {
		const manifest = JSON.parse(
			fs.readFileSync(path.join(packageDir, "package.json"), "utf8"),
		) as { version?: unknown };
		return typeof manifest.version === "string" ? manifest.version : "";
	} catch {
		return "";
	}
}

/** Read the Chromium revision this Playwright pins, or `-1` when unknown. */
function readChromiumRevision(): number {
	try {
		const registry = JSON.parse(
			fs.readFileSync(path.join(packageDir, "browsers.json"), "utf8"),
		) as { browsers?: Array<{ name?: string; revision?: unknown }> };
		const entry = registry.browsers?.find(
			(candidate) => candidate.name === "chromium",
		);
		const revision = entry?.revision;
		if (typeof revision === "number" && Number.isFinite(revision))
			return revision;
		if (typeof revision === "string") {
			const parsed = Number.parseInt(revision, 10);
			return Number.isFinite(parsed) ? parsed : -1;
		}
		return -1;
	} catch {
		return -1;
	}
}

const version = readVersion();
const revision = readChromiumRevision();
if (version === "" || revision < 0) {
	console.warn(
		"bundled-playwright.generated.ts: playwright-core is not installed; the install guard has no expected revision to enforce",
	);
}

const body = `// AUTO-GENERATED by scripts/generate-bundled-playwright.ts — do not edit.
// Regenerate after changing the playwright-core version: bun run scripts/generate-bundled-playwright.ts
/** The \`playwright-core\` version this build was made with, or \`""\` when unknown. */
export const BUNDLED_PLAYWRIGHT_VERSION: string = ${JSON.stringify(version)};
/** The Chromium revision this build's Playwright expects, or \`-1\` when unknown. */
export const BUNDLED_CHROMIUM_REVISION: number = ${revision};
`;
fs.writeFileSync(out, body);
console.log(
	`bundled playwright ${version || "(unknown)"} · chromium ${
		revision < 0 ? "(unknown)" : revision
	} -> ${path.relative(root, out)}`,
);
